/**
 * Antradus theme - the shipped content, in Arabic.
 *
 * This file is the mirror image of inc/defaults.php: the same keys, in the
 * same order, with the same section comments - only the words differ. Keeping
 * the two files parallel is the whole maintenance strategy. When a feature
 * changes, you open both files at the same section heading and edit the two
 * strings side by side; nothing has to be hunted for.
 *
 * Only the keys a reader sees are here. Links, images, colours, Freemius IDs
